#!/usr/bin/env python3
"""Package the Boost2Business Duet team (duet/skills/*) as self-contained skills.

Claude Duet inherits skills, memory and connectors from Karin's Claude account,
so the team ships as Claude skills. Each skill must stand alone (claude.ai
uploads them one by one), so every skill gets its own copy of:
  references/  business.md, conduct.md, rules.json, value-props.json,
               templates/email/*.md, the ops templates (WhatsApp, call script,
               quote, spec, go-live, support) and the call-summary example
  scripts/     client_folder.py (the client-folder engine)

Outputs:
  ops/duet/skills/<name>.zip   upload in claude.ai → Settings → Capabilities → Skills
  .claude/skills/<name>/       the same team for Claude Code sessions in this repo (generated: edit duet/, not here)

usage:  python3 tools/build_duet.py
"""
import json
import os
import re
import shutil
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DUET = os.path.join(ROOT, "duet")
OUT_ZIP = os.path.join(ROOT, "ops", "duet", "skills")
OUT_CC = os.path.join(ROOT, ".claude", "skills")

REFS = {  # published path inside references/ -> source (relative to ROOT)
    "business.md": "duet/shared/business.md",
    "conduct.md": "duet/shared/conduct.md",
    "rules.json": "duet/rules.json",
    "value-props.json": "duet/shared/value-props.json",
    "templates/whatsapp-replies.md": "templates/whatsapp-replies.md",
    "templates/discovery-call.md": "templates/discovery-call.md",
    "templates/quote.md": "templates/quote.md",
    "templates/spec.md": "templates/spec.md",
    "templates/go-live-checklist.md": "templates/go-live-checklist.md",
    "templates/support.md": "templates/support.md",
    "templates/call-summary.example.txt": "templates/examples/call-summary.example.txt",
}
FORBIDDEN = ["יד ימין", "קורא חוזים", "מחיר השקה"]


def frontmatter(path):
    s = open(path, encoding="utf-8").read()
    m = re.match(r"---\nname: (.+)\ndescription: (.+)\n---\n", s)
    if not m:
        raise SystemExit(f"{path}: frontmatter must be name + description")
    name, desc = m.group(1).strip(), json.loads(m.group(2))
    if not re.fullmatch(r"[a-z0-9-]{1,64}", name):
        raise SystemExit(f"{path}: bad skill name '{name}'")
    if len(desc) > 1024:
        raise SystemExit(f"{path}: description over 1024 characters")
    return name, desc


def check_text(path):
    t = open(path, encoding="utf-8").read()
    bad = [w for w in FORBIDDEN if w in t and "Never write" not in t and "אסור לכתוב" not in t and "never write" not in t.lower()]
    if bad:
        raise SystemExit(f"{path}: forbidden phrase {bad}")


def assemble(skill_dir, dst):
    if os.path.exists(dst):
        shutil.rmtree(dst)
    shutil.copytree(skill_dir, dst)
    for rel, src in REFS.items():
        p = os.path.join(dst, "references", rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        shutil.copy2(os.path.join(ROOT, src), p)
    edir = os.path.join(DUET, "shared", "templates", "email")
    for n in sorted(os.listdir(edir)):
        p = os.path.join(dst, "references", "templates", "email", n)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        shutil.copy2(os.path.join(edir, n), p)
    os.makedirs(os.path.join(dst, "scripts"), exist_ok=True)
    shutil.copy2(os.path.join(DUET, "scripts", "client_folder.py"), os.path.join(dst, "scripts", "client_folder.py"))


def main():
    os.makedirs(OUT_ZIP, exist_ok=True)
    os.makedirs(OUT_CC, exist_ok=True)
    for n in os.listdir(os.path.join(DUET, "shared", "templates", "email")):
        check_text(os.path.join(DUET, "shared", "templates", "email", n))
    names = []
    for n in sorted(os.listdir(os.path.join(DUET, "skills"))):
        sd = os.path.join(DUET, "skills", n)
        name, _ = frontmatter(os.path.join(sd, "SKILL.md"))
        if name != n:
            raise SystemExit(f"folder {n} != skill name {name}")
        cc = os.path.join(OUT_CC, name)
        assemble(sd, cc)
        z = os.path.join(OUT_ZIP, f"{name}.zip")
        with zipfile.ZipFile(z, "w", zipfile.ZIP_DEFLATED) as zf:
            for dp, _, fs in os.walk(cc):
                for f in sorted(fs):
                    full = os.path.join(dp, f)
                    zf.write(full, os.path.join(name, os.path.relpath(full, cc)))
        names.append((name, os.path.getsize(z)))
    readme = os.path.join(OUT_CC, "README.md")
    open(readme, "w", encoding="utf-8").write(
        "# Generated by tools/build_duet.py: edit duet/ and rebuild, not these copies.\n")
    for name, size in names:
        print(f"  {name:<20} {size / 1024:.0f} KB")
    print(f"{len(names)} skills → {os.path.relpath(OUT_ZIP, ROOT)}/*.zip and {os.path.relpath(OUT_CC, ROOT)}/")


if __name__ == "__main__":
    main()
